// Writes the time zones the app embeds from a release of the IANA time
// zone database: lib/core/time/zone_data.g.dart (the database's table of
// countries and zones, zone.tab, and the rules of every zone it names from
// 2025 on) and the server's copy of the same table,
// ../backend/crates/lunaway-conflate/data/zone.tab. From app/:
//
//   fvm dart run tool/time_zones/generate.dart <tzdata directory>
//
// <tzdata directory> is the release jiff-tzdb bundles in the backend
// (`jiff-tzdb` in backend/Cargo.lock; lunaway_conflate::time_zone holds the
// two to it), extracted from
// https://data.iana.org/time-zones/releases/tzdata<release>.tar.gz, whose
// signature (.asc, Paul Eggert's key) is checked first. zic, the
// database's own compiler, which macOS and Linux ship, compiles it; the
// timezone package reads the result and writes it in its own format. The
// steps: docs/architecture.md, "Time zones".
// The package's public API reads its format and none writes it: the
// serializer comes from its sources, as in its own encoder
// (tool/encode_tzf.dart).
import 'dart:convert';
import 'dart:io';

import 'package:timezone/src/tzdb.dart' show tzdbSerialize;
import 'package:timezone/timezone.dart' as tz;
import 'package:timezone/tzdata.dart' as tzif;

/// The first instant whose rules the app keeps: older times are never shown
/// on a place's clock, and the transitions before it would only weigh.
final int _from = DateTime.utc(2025).millisecondsSinceEpoch;

const _output = 'lib/core/time/zone_data.g.dart';
const _serverTable = '../backend/crates/lunaway-conflate/data/zone.tab';

/// The source files of the release, those `make` compiles by default.
const _sources = [
  'africa',
  'antarctica',
  'asia',
  'australasia',
  'europe',
  'northamerica',
  'southamerica',
  'etcetera',
  'backward',
];

Future<void> main(List<String> args) async {
  if (args.length != 1 || !File('${args.single}/zone.tab').existsSync()) {
    stderr.writeln('usage: fvm dart run tool/time_zones/generate.dart <tzdata directory>');
    exitCode = 64;
    return;
  }
  final source = args.single;
  final release = File('$source/version').readAsStringSync().trim();
  final table = File('$source/zone.tab').readAsStringSync();
  final rows = tzif.LocationDescriptionDatabase.fromString(table).locations;

  final compiled = Directory.systemTemp.createTempSync('lunaway-tzdata-');
  try {
    final zic = await Process.run('zic', [
      '-b',
      'fat',
      '-d',
      compiled.path,
      ..._sources,
    ], workingDirectory: source);
    if (zic.exitCode != 0) {
      stderr.writeln('zic failed: ${zic.stderr}');
      exitCode = 1;
      return;
    }
    final version = await Process.run('zic', ['--version']);
    final compiler = '${version.stdout}'.trim();
    final names = {for (final r in rows) r.name, 'Europe/Paris'}.toList()..sort();
    final database = tz.LocationDatabase();
    for (final name in names) {
      final bytes = File('${compiled.path}/$name').readAsBytesSync();
      database.add(_trimmed(_native(tzif.Location.fromBytes(name, bytes))));
    }
    final rules = base64.encode(tzdbSerialize(database));
    File(_output).writeAsStringSync(_dart(release, compiler, rows, rules));
    File(_serverTable).writeAsStringSync(table);
    stdout.writeln(
      'tzdata $release: ${rows.length} rows, ${names.length} zones, '
      '${rules.length} base64 characters of rules -> $_output, $_serverTable',
    );
  } finally {
    compiled.deleteSync(recursive: true);
  }
}

/// [location] as the package's runtime type: milliseconds, and each zone
/// with its abbreviation.
tz.Location _native(tzif.Location location) => tz.Location(
  location.name,
  [for (final at in location.transitionAt) at * 1000],
  location.transitionZone,
  [
    for (final z in location.zones)
      tz.TimeZone(
        Duration(seconds: z.offset),
        isDst: z.isDst,
        abbreviation: location.abbreviations[z.abbreviationIndex],
      ),
  ],
);

/// [location] from [_from] on: the zone in force at [_from] from the
/// beginning of time, then the later transitions, and only the zones they
/// use.
tz.Location _trimmed(tz.Location location) {
  final at = location.transitionAt;
  var first = 0;
  while (first < at.length && at[first] <= _from) {
    first++;
  }
  // A zone that never changed before [_from] keeps its history.
  if (first == 0) return location;
  final kept = [location.transitionZone[first - 1], ...location.transitionZone.sublist(first)];
  final used = <int>[];
  for (final z in kept) {
    if (!used.contains(z)) used.add(z);
  }
  return tz.Location(
    location.name,
    [tz.TZDateTime.minMillisecondsSinceEpoch, ...at.sublist(first)],
    [for (final z in kept) used.indexOf(z)],
    [for (final z in used) location.zones[z]],
  );
}

String _dart(String release, String compiler, List<tzif.LocationDescription> rows, String rules) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/time_zones/generate.dart from tzdata $release. Do not edit.')
    ..writeln('// Compiled by $compiler.')
    ..writeln('//')
    ..writeln('// The IANA time zone database (https://www.iana.org/time-zones), in the')
    ..writeln('// public domain: its table of countries and zones, zone.tab, and the rules')
    ..writeln('// of every zone the table names from 2025 on.')
    ..writeln('library;')
    ..writeln()
    ..writeln('/// The release of the database, the one the server bundles too.')
    ..writeln("const tzdataRelease = '$release';")
    ..writeln()
    ..writeln('/// zone.tab: a country (ISO 3166-1 alpha-2), one of its zones, and the')
    ..writeln("/// zone's principal location (latitude, longitude).")
    ..writeln('const zoneCentres = <(String, String, double, double)>[');
  for (final r in rows) {
    out.writeln("  ('${r.countryCodes.single}', '${r.name}', ${r.latitude}, ${r.longitude}),");
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln("/// The rules of those zones, in package:timezone's format, base64.")
    ..writeln('const zoneRules =');
  const width = 96;
  for (var i = 0; i < rules.length; i += width) {
    final end = i + width < rules.length ? i + width : rules.length;
    out
      ..write("    '${rules.substring(i, end)}'")
      ..writeln(end == rules.length ? ';' : '');
  }
  return out.toString();
}
